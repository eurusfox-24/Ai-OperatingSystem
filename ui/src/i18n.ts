let currentLanguage: SupportedLanguage = 'en';

export function setLanguage(lang: SupportedLanguage) {
  currentLanguage = lang;
  localStorage.setItem('os_language', lang);
  applyTranslations();
  // Dispatch an event so other parts of the app (like Kanban board rendering) can re-render if needed
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
}

export function getLanguage(): SupportedLanguage {
  return currentLanguage;
}

export function initI18n() {
  const savedLang = localStorage.getItem('os_language') as SupportedLanguage;
  if (savedLang && (savedLang === 'en' || savedLang === 'fi')) {
    currentLanguage = savedLang;
  }
  applyTranslations();
}

export function t(key: string): string {
  if (translations[currentLanguage] && translations[currentLanguage][key]) {
    return translations[currentLanguage][key];
  }
  // Fallback to English, then to the key itself
  if (translations['en'] && translations['en'][key]) {
    return translations['en'][key];
  }
  return key;
}

export function applyTranslations() {
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      const translation = t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        (el as HTMLInputElement).placeholder = translation;
      } else if (el.tagName === 'OPTION') {
        el.textContent = translation;
      } else {
        // If element has child element nodes (e.g. SVGs, badges, arrows), only replace text node content
        const childNodes = Array.from(el.childNodes);
        const textNode = childNodes.find(node => node.nodeType === Node.TEXT_NODE && (node.textContent?.trim().length || 0) > 0);
        if (textNode) {
          // Preserve trailing or leading whitespace/symbols if present (e.g., dropdown arrow)
          const orig = textNode.textContent || '';
          if (orig.includes('▾')) {
            textNode.textContent = `${translation} ▾`;
          } else {
            textNode.textContent = translation;
          }
        } else if (el.children.length === 0) {
          el.textContent = translation;
        }
      }
    }
  });
}
